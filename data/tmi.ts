/** 랜덤 TMI 1개 반환 */
export function getRandomTMI(): string {
  return CAR_TMI[Math.floor(Math.random() * CAR_TMI.length)];
}

/** 랜덤 TMI n개 반환 (중복 없이) */
export function getRandomTMIs(count: number): string[] {
  const shuffled = [...CAR_TMI].sort(() => Math.random() - 0.5);
  return shuffled.slice(0, Math.min(count, CAR_TMI.length));
}
