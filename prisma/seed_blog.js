async function main() {
  console.log("🌱 픽스카 블로그 시드 시작\n");

  /* 1) 커버 디렉토리 */
  const coverDir = path.join(__dirname, "..", "public", "blog-covers");
  fs.mkdirSync(coverDir, { recursive: true });

  /* 2) SVG 커버 생성 */
  for (const a of articles) {
    const svg = makeSvg({ title: a.title, category: a.category, icon: a.icon, accent: ACCENT[a.category] });
    fs.writeFileSync(path.join(coverDir, `${a.slug}.svg`), svg, "utf8");
  }
  console.log(`🖼  커버 ${articles.length}장 생성 → public/blog-covers/`);

  /* 3) 작성자 확인 */
  const author = await prisma.user.findUnique({ where: { id: AUTHOR_ID } });
  if (!author) throw new Error(`작성자(User id=${AUTHOR_ID})가 없습니다.`);
  console.log(`👤 작성자: ${author.name} (id=${author.id})`);

  /* 4) 빈 테스트 글 정리 */
  const del = await prisma.blogPost.deleteMany({ where: { title: "테스트" } });
  console.log(`🗑  테스트 글 ${del.count}개 삭제`);

  /* 5) 글 20개 생성 (중복 title skip) */
  let created = 0,
    skipped = 0;
  for (const a of articles) {
    const exists = await prisma.blogPost.findFirst({ where: { title: a.title } });
    if (exists) {
      skipped++;
      console.log(`  ⏭  이미 존재: ${a.title}`);
      continue;
    }
    await prisma.blogPost.create({
      data: {
        title: a.title,
        category: a.category,
        content: a.content,
        summary: `/blog-covers/${a.slug}.svg`,
        tags: a.tags,
        authorId: AUTHOR_ID,
        published: true,
      },
    });
    created++;
    console.log(`  ✅ ${a.category} | ${a.title}`);
  }

  console.log(`\n🎉 완료 — 생성 ${created}개 / 스킵 ${skipped}개`);
}

main()
  .catch((e) => {
    console.error("❌ 시드 에러:", e);
    process.exit(1);
  })
  .finally(() => prisma.$disconnect());
